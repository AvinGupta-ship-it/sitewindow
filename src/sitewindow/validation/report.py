"""Human-readable summary of ``validation_report.json`` (manual C8)."""

from __future__ import annotations

from typing import Any


def _status(passed: bool | None) -> str:
    if passed is None:
        return "reported"
    return "pass" if passed else "fail"


def render_markdown(report: dict[str, Any], not_listed: str | None = None) -> str:
    """Markdown table of one row per benchmark with status and summary."""
    tier = report.get("tier", "verify")
    lines = [
        f"# Validation report ({tier} tier)",
        "",
        f"Thresholds: `data/registry/benchmarks.yaml`. Generated by `sitewindow validate --tier {tier}`.",
        "Status `reported` marks runners that report a value without a pass criterion at this tier.",
        "",
        "| ID | Result | Summary |",
        "|---|---|---|",
    ]
    for r in report["benchmarks"]:
        summary = str(r.get("summary", "")).replace("|", "/")
        lines.append(f"| {r['id']} | {_status(r.get('passed'))} | {summary} |")
    if not_listed:
        lines += ["", not_listed]
    return "\n".join(lines) + "\n"


__all__ = ["render_markdown"]
